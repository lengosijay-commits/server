app.get("/health", async (req, res) => {
  try {
    await pool.query("SELECT 1");
    res.status(200).json({ status: "ok", database: "connected" });
  } catch (error) {
    console.error("Health check failed:", error.message);
    res.status(503).json({ message: "Database is not responding." });
  }
});

app.use("/api/records", require("./routes/records"));

app.use((req, res) => {
  res.status(404).json({ message: "Route not found." });
});

app.use((error, req, res, next) => {
  if (error.type === "entity.parse.failed" || error instanceof SyntaxError) {
    return res.status(400).json({ message: "Malformed JSON in request body." });
  }
  console.error(error);
  res.status(500).json({ message: "Unexpected server error." });
});

// Create the table and seed it once, only when the table is empty.
async function initDatabase() {
  const read = name => fs.readFileSync(path.join(__dirname, name), "utf8");
  await pool.query(read("schema.sql"));
  const { rows } = await pool.query("SELECT COUNT(*) AS n FROM records");
  if (Number(rows[0].n) === 0) {
    await pool.query(read("seed.sql"));
    console.log("Seeded records.");
  }
}

const port = process.env.PORT || 3000;
initDatabase()
  .catch(error => console.error("Database setup failed:", error.message))
  .finally(() => {
    app.listen(port, "0.0.0.0", () => {
      console.log(`Server listening on port ${port}`);
    });
  });
